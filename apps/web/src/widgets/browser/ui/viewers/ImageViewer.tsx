import React from 'react';
import { useFilePreviewStore } from '../../model/useFilePreviewStore';
import { Image as ImageIcon, Download } from 'lucide-react';

export const ImageViewer: React.FC = () => {
  const { currentFile, zoom, rotation } = useFilePreviewStore();

  if (!currentFile) return null;

  const imageUrl = currentFile.url || currentFile.path || '';

  const handleDownload = () => {
    if (imageUrl) {
      const a = document.createElement('a');
      a.href = imageUrl;
      a.download = currentFile.name;
      a.click();
    }
  };

  return (
    <div className="w-full h-full flex flex-col items-center justify-center bg-[#07080E] p-6 relative select-none overflow-hidden">
      {/* Image Canvas Container */}
      <div className="flex-1 w-full flex items-center justify-center min-h-0 relative overflow-hidden">
        {imageUrl ? (
          <img
            src={imageUrl}
            alt={currentFile.name}
            style={{
              transform: `scale(${zoom / 100}) rotate(${rotation}deg)`,
              transformOrigin: 'center center',
            }}
            className="max-w-full max-h-full object-contain rounded-lg shadow-2xl transition-transform duration-200"
          />
        ) : (
          /* High-Fidelity SVG Graphic Preview Mock Canvas */
          <div
            style={{
              transform: `scale(${zoom / 100}) rotate(${rotation}deg)`,
              transformOrigin: 'center center',
            }}
            className="w-[420px] h-[280px] bg-gradient-to-tr from-purple-950/60 via-[#111428] to-indigo-950/60 border border-white/10 rounded-2xl p-6 shadow-2xl flex flex-col justify-between relative overflow-hidden transition-transform duration-200"
          >
            {/* Radial Glow */}
            <div className="absolute top-1/2 left-1/2 -translate-x-1/2 -translate-y-1/2 w-48 h-48 bg-[#00DFFF]/10 rounded-full blur-3xl pointer-events-none" />

            <div className="flex items-center justify-between relative z-10">
              <div className="flex items-center space-x-2">
                <ImageIcon className="w-4 h-4 text-purple-400" />
                <span className="font-mono text-xs font-bold text-white">{currentFile.name}</span>
              </div>
              <span className="px-2 py-0.5 rounded-full bg-white/10 text-[9px] font-mono text-white/70">
                1920 × 1080 • PNG
              </span>
            </div>

            <div className="text-center space-y-1 relative z-10 my-auto">
              <div className="w-12 h-12 mx-auto rounded-2xl bg-gradient-to-tr from-purple-500 to-indigo-500 flex items-center justify-center shadow-lg shadow-purple-500/30 text-white font-extrabold text-lg">
                N
              </div>
              <h2 className="text-base font-extrabold tracking-wide text-white">NEXORA HERO GRAPHIC</h2>
              <p className="text-[10px] font-mono text-white/50">High-Resolution Asset • Generated by JARVIS</p>
            </div>

            <div className="flex items-center justify-between text-[9px] font-mono text-white/40 relative z-10 border-t border-white/10 pt-2">
              <span>Aspect Ratio 16:9</span>
              <span>RGB 24-bit</span>
            </div>
          </div>
        )}
      </div>

      {/* Floating Info & Download Bar */}
      <div className="mt-2 flex items-center space-x-3 px-3 py-1.5 rounded-full bg-[#121424]/90 border border-white/10 backdrop-blur-md text-[10px] font-mono text-white/70 shadow-xl">
        <span className="text-white font-semibold">{currentFile.name}</span>
        <span className="text-white/20">•</span>
        <span>Zoom: {zoom}%</span>
        <span className="text-white/20">•</span>
        <span>Rotation: {rotation}°</span>
        <button
          onClick={handleDownload}
          className="ml-2 px-2 py-0.5 rounded bg-white/10 hover:bg-white/20 text-white flex items-center space-x-1 transition-colors"
        >
          <Download className="w-3 h-3 text-[#00DFFF]" />
          <span>Save</span>
        </button>
      </div>
    </div>
  );
};
